const CACHE_NAME = "nutriscan-cache-v2";
const APP_SHELL = ["./", "./manifest.json"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  // Never cache external API calls (Open Food Facts, Gemini) - always go to network.
  if (url.origin !== self.location.origin) return;

  // Network-first: this app ships frequent updates, so a visitor should
  // always see the latest deploy when online. The cache exists purely as an
  // offline fallback, not as a way to skip the network on a good connection
  // (that previously left people stuck on stale JS/HTML indefinitely).
  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response && response.status === 200) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, clone));
        }
        return response;
      })
      .catch(() => caches.match(request))
  );
});
